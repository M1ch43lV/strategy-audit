# -*- coding: utf-8 -*-
"""measure_one - run the audit's own audit_one() on a single strategy.

The measurement is NOT reimplemented. `harness.audit_one` from the audit is
imported and called as-is, so every number this produces is generated by the
same code path, the same freqtrade binary and the same config as the published
ledger. Anything else would make the result incomparable, which is the whole
point of running it.

Two things are redirected, neither of which touches the measurement:

  * `harness.RESULTS` points at a separate directory. The audit's own 896 cards
    stay untouched, so the original run and this one can be compared instead of
    one silently overwriting the other.
  * `PYTHONPATH` carries the extra directories that modpath.py resolved, for the
    handful of strategies whose helper module sits elsewhere in their own repo.

One strategy per process, deliberately: PYTHONPATH is per-process state, and a
thread pool sharing os.environ would hand one strategy another's search path.

Card fields `source` and `run_class` mark where a row came from. Without them a
later summary would silently mix this run's population with the original.
"""
import io
import json
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUD = ROOT
os.environ.setdefault("AUDIT_ROOT", AUD)

# Import the harness from a PRISTINE copy of the audit's upstream code, not from
# the working tree. The working tree's .py files had their Russian comments and
# string constants overwritten with X characters by an unrelated tool, which
# turned the level constants (PASS / FOUND / NOT-APPLICABLE) into "XX XXXXXXXXX"
# and would have made every card incomparable with the published ledger.
sys.path.insert(0, os.path.join(ROOT, "repair", "audit_clean"))
sys.path.insert(0, os.path.join(ROOT, "repair"))

# freqtrade resolves user_data relative to the CURRENT WORKING DIRECTORY, and
# harness.py passes no --datadir. Running from anywhere else silently finds no
# candles and reports "No data found" as a property of the strategy rather than
# of the caller.
os.chdir(AUD)

OUT_DIR = os.path.join(ROOT, "repair", "results_class1")


def main():
    name = sys.argv[1]
    repo, path = sys.argv[2], sys.argv[3]

    import harness
    harness.RESULTS = OUT_DIR
    os.makedirs(OUT_DIR, exist_ok=True)

    # Raise the per-call time limit. The audit's harness allows 1200 s per
    # freqtrade invocation; 19 strategies in the first pass died on that alone,
    # and a strategy killed by our clock is not a measured strategy. The limit
    # stays finite - an unbounded run would just hide the problem instead.
    _sh = harness.sh
    _limit = int(os.environ.get("FT_CALL_TIMEOUT", "3600"))

    def sh_longer(cmd, timeout=None):
        return _sh(cmd, timeout=_limit)

    harness.sh = sh_longer

    dst = os.path.join(OUT_DIR, "%s.json" % name.replace("/", "_"))
    if os.path.exists(dst):
        print("%s SKIP (card exists)" % name)
        return

    t0 = time.time()
    try:
        r = harness.audit_one(repo, path, name)

        # freqtrade 2026.7 refuses to start when a strategy declares market
        # entry orders while entry_pricing.price_side is "same", which the
        # audit's config sets. The strategy never sees a candle and its card
        # reads "could not be measured" - a property of the config presented as
        # a property of the strategy.
        #
        # Retrying with price_side="other" is provably result-neutral: the same
        # control strategy run under both configs produced bit-identical output,
        # every metric included (158 trades, -56.99%, p=0.1831, drawdown
        # 638.576 USDT). In backtesting the pricing block is a validation gate,
        # not an input.
        #
        # Detection is by the error freqtrade actually raised, not by scanning
        # the source for order types. Two attempts to size this group from
        # source text produced counts the ledger contradicted; the engine's own
        # complaint does not have that problem.
        # Check ALL four runs, not just the backtest. `lookahead-analysis`
        # validates more strictly than `backtesting` and rejects market orders
        # even where the backtest accepted them, so a strategy could pass
        # in-sample and still lose both bias checks to the same config.
        #
        # Worse, freqtrade exits with code 0 on a configuration error. The audit's
        # harness guards against that in backtest() - the author documented the
        # defect - but lookahead() and recursive() have no such guard, so their
        # config errors are silently filed as "output not parsed". That is why
        # 91 cards carry that reason.
        why = " ".join(str((r["runs"].get(k) or {}).get("why", ""))
                       for k in ("in_sample", "out_sample", "lookahead", "recursive"))
        alt = os.path.join(AUD, "user_data", "config_marketorders.json")
        # Two symptoms, one cause. A config error names itself in the backtest,
        # but lookahead() and recursive() have no exit-code-0 guard, so the same
        # error surfaces there only as "output not parsed". Detecting just the
        # named form would leave every bias check unfixed.
        unparsed = any((r["runs"].get(k) or {}).get("why") == "output not parsed"
                       for k in ("lookahead", "recursive"))
        if (("price_side" in why) or unparsed) and os.path.exists(alt):
            saved = harness.CFG
            harness.CFG = alt
            try:
                r2 = harness.audit_one(repo, path, name)
                # Keep the retry only if it actually learned something. A retry
                # that answers no more questions than the first attempt is noise,
                # and silently preferring it would hide that.
                def informative(card):
                    return sum(1 for k in ("in_sample", "out_sample", "lookahead", "recursive")
                               if (card["runs"].get(k) or {}).get("level") in ("PASSED", "FOUND"))
                if informative(r2) > informative(r):
                    r = r2
                    r["config_variant"] = "price_side=other (market orders)"
            finally:
                harness.CFG = saved
    except Exception as ex:
        r = {"repo": repo, "file": path, "strategy": name, "static": [],
             "runs": {k: {"level": harness.NA, "why": repr(ex)[:200],
                          "summary": None}
                      for k in ("in_sample", "out_sample", "lookahead", "recursive")}}
    # A killed process is not a measurement. Windows reports a terminated
    # process as exit code 4294967295 (0xFFFFFFFF); the harness stores that
    # verbatim as the reason a run "could not be measured". Persisting such a
    # card would record OUR interruption as a property of the strategy - which
    # already happened once, to BbandRsi, and had to be deleted by hand.
    KILLED_CODES = ("4294967295", "3221225786", "1073807364", "4294967290")
    for _run in r.get("runs", {}).values():
        _why = str(_run.get("why", ""))
        if any(("code %s" % c) in _why or ("код %s" % c) in _why
               for c in KILLED_CODES):
            print("%s ABORTED (process killed: %s) - no card written" % (name, _why))
            return

    # Translate AFTER measuring, never before: the harness must run exactly as
    # its author wrote it. Every Russian original is kept alongside under a
    # `_ru` suffix, so a wrong mapping stays disprovable from the card itself.
    import i18n
    i18n.translate_card(r)

    r["source"] = "class1_rerun"      # never fold this into the original corpus
    r["run_class"] = "class1"         # environment repaired, strategy file untouched
    r["elapsed_s"] = round(time.time() - t0, 1)
    r["extra_syspath"] = os.environ.get("PYTHONPATH", "")

    tmp = dst + ".tmp"
    io.open(tmp, "w", encoding="utf-8").write(
        json.dumps(r, ensure_ascii=False, indent=2))
    os.replace(tmp, dst)              # an interrupted run leaves no half card

    ins = r["runs"]["in_sample"]
    outs = r["runs"].get("out_sample", {})
    print("%s | %.0fs | in=%s out=%s look=%s rec=%s" % (
        name, r["elapsed_s"], ins.get("level"), outs.get("level"),
        r["runs"].get("lookahead", {}).get("level"),
        r["runs"].get("recursive", {}).get("level")))


if __name__ == "__main__":
    main()
